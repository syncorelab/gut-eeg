def plot_losses_errors(
    train_losses: List[float],
    test_losses: List[float],
    train_errors: List[float],
    test_errors: List[float],
    error_is_fraction: bool = True,
) -> None:
    """
    Plot train/test loss and train/test error curves in two subplots.

    Parameters
    ----------
    train_losses : list of float
        Average training loss per epoch.
    test_losses : list of float
        Average test loss per epoch.
    train_errors : list of float
        Training error per epoch. If error_is_fraction=True, values are in [0,1].
    test_errors : list of float
        Test error per epoch. Same convention as train_errors.
    error_is_fraction : bool
        If True, errors are assumed to be in [0,1] and are converted to percent.
        If False, they are plotted as-is (assumed already in %).
    """
    train_losses = np.asarray(train_losses)
    test_losses = np.asarray(test_losses)
    train_errors = np.asarray(train_errors)
    test_errors = np.asarray(test_errors)

    if error_is_fraction:
        train_err_plot = train_errors * 100.0
        test_err_plot = test_errors * 100.0
    else:
        train_err_plot = train_errors
        test_err_plot = test_errors

    fig, ax = plt.subplots(1, 2, figsize=(16, 5))

    # Loss curve
    ax[0].plot(train_losses, 's-', label='Train')
    ax[0].plot(test_losses, 'o-', label='Test')
    ax[0].set_xlabel('Epochs')
    ax[0].set_ylabel('Loss')
    ax[0].set_title('Model loss')
    ax[0].legend()

    # Error curve
    ax[1].plot(train_err_plot, 's-', label='Train')
    ax[1].plot(test_err_plot, 'o-', label='Test')
    ax[1].set_xlabel('Epochs')
    ax[1].set_ylabel('Error rate (%)')
    ax[1].set_title(f'Final model test error rate: {test_err_plot[-1]:.2f}%')
    ax[1].legend()

    plt.tight_layout()
    plt.show()