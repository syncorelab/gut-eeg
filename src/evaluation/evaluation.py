from typing import List, Tuple, Dict, Optional

import numpy as np
import torch
import torch.nn as nn
import matplotlib.pyplot as plt
from sklearn.metrics import confusion_matrix, classification_report


# -------------------------------------------------------------------------
# Basic metrics
# -------------------------------------------------------------------------

def compute_accuracy(outputs: torch.Tensor, targets: torch.Tensor) -> float:
    """
    Compute accuracy for a batch.

    Parameters
    ----------
    outputs : torch.Tensor
        Model outputs (logits or probabilities) of shape (batch_size, num_classes).
    targets : torch.Tensor
        Ground-truth class indices of shape (batch_size,).

    Returns
    -------
    float
        Accuracy in [0, 1].
    """
    preds = outputs.argmax(dim=1)
    correct = (preds == targets).sum().item()
    total = targets.size(0)
    return correct / total


