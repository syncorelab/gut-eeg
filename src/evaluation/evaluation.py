def evaluate_on_new_subject(
    model: nn.Module,
    dataloader: torch.utils.data.DataLoader,
    criterion: Optional[nn.Module] = None,
    device: Optional[torch.device] = None,
) -> Tuple[float, float]:
    """
    Evaluate a trained model on a dataloader (e.g., one subject's windows).

    Parameters
    ----------
    model : nn.Module
        Trained model.
    dataloader : DataLoader
        DataLoader with (inputs, targets) for ONE subject or dataset split.
    criterion : loss function, optional
        Loss function. If None, uses CrossEntropyLoss.
    device : torch.device, optional
        Device to run evaluation on. If None, inferred from model.

    Returns
    -------
    avg_loss : float
        Average loss over all samples.
    accuracy : float
        Accuracy in [0, 1] over all samples.
    """
    model.eval()
    if device is None:
        device = next(model.parameters()).device
    if criterion is None:
        criterion = nn.CrossEntropyLoss()

    running_loss = 0.0
    running_correct = 0
    n_samples = 0

    with torch.no_grad():
        for inputs, targets in dataloader:
            inputs = inputs.to(device)
            targets = targets.to(device)

            outputs = model(inputs)
            loss = criterion(outputs, targets)

            batch_size = inputs.size(0)
            running_loss += loss.item() * batch_size

            preds = outputs.argmax(dim=1)
            running_correct += (preds == targets).sum().item()
            n_samples += batch_size

    avg_loss = running_loss / n_samples
    accuracy = running_correct / n_samples
    return avg_loss, accuracy


