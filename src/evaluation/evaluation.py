def compute_confusion_matrix(
    model: nn.Module,
    dataloader: torch.utils.data.DataLoader,
    device: Optional[torch.device] = None,
    normalize: bool = False,
) -> np.ndarray:
    """
    Compute confusion matrix over all samples in a dataloader.

    Parameters
    ----------
    model : nn.Module
        Trained model.
    dataloader : DataLoader
        DataLoader with (inputs, targets).
    device : torch.device, optional
        Device to run evaluation on. If None, inferred from model.
    normalize : bool
        If True, returns row-normalized confusion matrix (per-class).

    Returns
    -------
    np.ndarray
        Confusion matrix of shape (num_classes, num_classes).
    """
    model.eval()
    if device is None:
        device = next(model.parameters()).device

    all_preds = []
    all_targets = []

    with torch.no_grad():
        for inputs, targets in dataloader:
            inputs = inputs.to(device)
            targets = targets.to(device)

            outputs = model(inputs)
            preds = outputs.argmax(dim=1)

            all_preds.append(preds.cpu().numpy())
            all_targets.append(targets.cpu().numpy())

    all_preds = np.concatenate(all_preds)
    all_targets = np.concatenate(all_targets)

    cm = confusion_matrix(
        all_targets,
        all_preds,
        normalize="true" if normalize else None,
    )
    return cm


def compute_per_class_metrics(
    model: nn.Module,
    dataloader: torch.utils.data.DataLoader,
    device: Optional[torch.device] = None,
    target_names: Optional[List[str]] = None,
) -> Dict:
    """
    Compute per-class precision, recall, f1-score, and support.

    Parameters
    ----------
    model : nn.Module
        Trained model.
    dataloader : DataLoader
        DataLoader with (inputs, targets).
    device : torch.device, optional
        Device to run evaluation on. If None, inferred from model.
    target_names : list of str, optional
        Names of the classes (e.g. ["calm", "fear", "hunger"]).
        If None, class labels (0,1,2,...) are used.

    Returns
    -------
    dict
        Dictionary as returned by sklearn.metrics.classification_report(output_dict=True).
        Keys include per-class metrics and "macro avg", "weighted avg".
    """
    model.eval()
    if device is None:
        device = next(model.parameters()).device

    all_preds = []
    all_targets = []

    with torch.no_grad():
        for inputs, targets in dataloader:
            inputs = inputs.to(device)
            targets = targets.to(device)

            outputs = model(inputs)
            preds = outputs.argmax(dim=1)

            all_preds.append(preds.cpu().numpy())
            all_targets.append(targets.cpu().numpy())

    all_preds = np.concatenate(all_preds)
    all_targets = np.concatenate(all_targets)

    report = classification_report(
        all_targets,
        all_preds,
        target_names=target_names,
        output_dict=True,
        zero_division=0,
    )
    return report


